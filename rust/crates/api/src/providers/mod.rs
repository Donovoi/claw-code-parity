#[must_use]
pub fn resolve_model_alias(model: &str) -> String {
    let trimmed = model.trim();
    let lower = trimmed.to_ascii_lowercase();
    MODEL_REGISTRY
        .iter()
        .find_map(|(alias, metadata)| {
            (*alias == lower).then_some(match metadata.provider {
                ProviderKind::Anthropic => match *alias {
                    "opus" => "claude-opus-4-6",
                    "sonnet" => "claude-sonnet-4-6",
                    "haiku" => "claude-haiku-4-5-20251213",
                    _ => trimmed,
                },
                ProviderKind::Xai => match *alias {
                    "grok" | "grok-3" => "grok-3",
                    "grok-mini" | "grok-3-mini" => "grok-3-mini",
                    "grok-2" => "grok-2",
                    _ => trimmed,
                },
                ProviderKind::OpenAi => match *alias {
                    "gpt5" | "gpt-5" => "gpt-5",
                    "gpt-5-mini" => "gpt-5-mini",
                    "gpt-5.4" => "gpt-5.4",
                    "gpt-5.4-mini" => "gpt-5.4-mini",
                    "gpt-4.1" => "gpt-4.1",
                    "gpt-4o" => "gpt-4o",
                    "o4-mini" => "o4-mini",
                    _ => trimmed,
                },
            })
        })
        .map_or_else(|| trimmed.to_string(), ToOwned::to_owned)
}

#[must_use]
pub fn metadata_for_model(model: &str) -> Option<ProviderMetadata> {
    let canonical = resolve_model_alias(model);
    if canonical.starts_with("claude") {
        return Some(ProviderMetadata {
            provider: ProviderKind::Anthropic,
            auth_env: "ANTHROPIC_API_KEY",
            base_url_env: "ANTHROPIC_BASE_URL",
            default_base_url: anthropic::DEFAULT_BASE_URL,
        });
    }
    if canonical.starts_with("grok") {
        return Some(ProviderMetadata {
            provider: ProviderKind::Xai,
            auth_env: "XAI_API_KEY",
            base_url_env: "XAI_BASE_URL",
            default_base_url: openai_compat::DEFAULT_XAI_BASE_URL,
        });
    }
    if canonical.starts_with("gpt-")
        || canonical.starts_with("chatgpt-")
        || canonical.starts_with("o1")
        || canonical.starts_with("o3")
        || canonical.starts_with("o4")
    {
        return Some(ProviderMetadata {
            provider: ProviderKind::OpenAi,
            auth_env: "OPENAI_API_KEY",
            base_url_env: "OPENAI_BASE_URL",
            default_base_url: openai_compat::DEFAULT_OPENAI_BASE_URL,
        });
    }
    None
}

#[must_use]
pub const fn default_model_for_provider(provider: ProviderKind) -> &'static str {
    match provider {
        ProviderKind::Anthropic => DEFAULT_ANTHROPIC_MODEL,
        ProviderKind::Xai => DEFAULT_XAI_MODEL,
        ProviderKind::OpenAi => DEFAULT_OPENAI_MODEL,
    }
}

#[must_use]
pub fn default_model_for_available_credentials() -> &'static str {
    if anthropic::has_auth_from_env_or_saved().unwrap_or(false) {
        return DEFAULT_ANTHROPIC_MODEL;
    }
    if openai_compat::has_api_key("OPENAI_API_KEY") {
        return DEFAULT_OPENAI_MODEL;
    }
    if openai_compat::has_api_key("XAI_API_KEY") {
        return DEFAULT_XAI_MODEL;
    }
    DEFAULT_ANTHROPIC_MODEL
}

#[must_use]
pub fn detect_provider_kind(model: &str) -> ProviderKind {
    if let Some(metadata) = metadata_for_model(model) {
        return metadata.provider;
    }
    if anthropic::has_auth_from_env_or_saved().unwrap_or(false) {
        return ProviderKind::Anthropic;
    }
    if openai_compat::has_api_key("OPENAI_API_KEY") {
        return ProviderKind::OpenAi;
    }
    if openai_compat::has_api_key("XAI_API_KEY") {
        return ProviderKind::Xai;
    }
    ProviderKind::Anthropic
}

#[must_use]
pub fn max_tokens_for_model(model: &str) -> u32 {
    let canonical = resolve_model_alias(model);
    if canonical.contains("opus") {
        return DEFAULT_OPUS_MAX_TOKENS;
    }

    if metadata_for_model(&canonical).is_some() {
        return DEFAULT_KNOWN_MODEL_MAX_TOKENS;
    }

    DEFAULT_UNKNOWN_MODEL_MAX_TOKENS
}

#[cfg(test)]
mod tests {
    use super::{
        default_model_for_provider, detect_provider_kind, max_tokens_for_model,
        resolve_model_alias, ProviderKind, DEFAULT_OPENAI_MODEL, DEFAULT_XAI_MODEL,
    };

    #[test]
    fn resolves_grok_aliases() {
        assert_eq!(resolve_model_alias("grok"), "grok-3");
        assert_eq!(resolve_model_alias("grok-mini"), "grok-3-mini");
        assert_eq!(resolve_model_alias("grok-2"), "grok-2");
    }

    #[test]
    fn resolves_openai_aliases() {
        assert_eq!(resolve_model_alias("gpt5"), "gpt-5");
        assert_eq!(resolve_model_alias("gpt-5.4"), "gpt-5.4");
        assert_eq!(resolve_model_alias("o4-mini"), "o4-mini");
    }

    #[test]
    fn detects_provider_from_model_name_first() {
        assert_eq!(detect_provider_kind("grok"), ProviderKind::Xai);
        assert_eq!(
            detect_provider_kind("claude-sonnet-4-6"),
            ProviderKind::Anthropic
        );
        assert_eq!(detect_provider_kind("gpt-5"), ProviderKind::OpenAi);
    }

    #[test]
    fn keeps_existing_max_token_heuristic() {
        assert_eq!(max_tokens_for_model("opus"), 32_000);
        assert_eq!(max_tokens_for_model("grok-3"), 64_000);
        assert_eq!(max_tokens_for_model("gpt-5"), 64_000);
    }

    #[test]
    fn uses_conservative_cap_for_unknown_models() {
        assert_eq!(max_tokens_for_model("Qwen/Qwen3-0.6B"), 1_024);
        assert_eq!(max_tokens_for_model("local-llama"), 1_024);
    }

    #[test]
    fn returns_provider_defaults() {
        assert_eq!(
            default_model_for_provider(ProviderKind::OpenAi),
            DEFAULT_OPENAI_MODEL
        );
        assert_eq!(
            default_model_for_provider(ProviderKind::Xai),
            DEFAULT_XAI_MODEL
        );
    }
}
